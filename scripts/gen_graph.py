"""Write a self-contained ACT file for one decomposed layer or the full model.

ACT template parameters are fixed per instance, so the 28 block instances are
written out explicitly rather than declared as an array.

Usage:
    gen_graph.py layer <L> <out.act>
    gen_graph.py model <out.act>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def top_layer(layer: int) -> str:
    return f"""
defproc top()
{{
  layer_source<{layer}> src;
  block<{layer}> b;
  layer_sink sink;
  src.O = b.I;
  b.O = sink.I;
}}
"""


def top_model() -> str:
    cfg = json.loads((ROOT / "config" / "model.json").read_text())
    stages = json.loads((ROOT / "config" / "stage_map.json").read_text())
    n = cfg["num_hidden_layers"]
    base = stages["top_level_layer_base"] * 16
    ops = stages["top_level_ops"]
    lines = ["defproc top()", "{", "  generation_controller ctl;",
             f"  mem_stage1<{base + ops['embed']}> embed;"]
    lines += [f"  block<{i}> b{i};" for i in range(n)]
    lines += [f"  mem_stage1<{base + ops['final_norm']}> final_norm;",
              f"  mem_stage1<{base + ops['lm_head']}> lm_head;",
              f"  mem_stage1<{base + ops['select']}> select;",
              "",
              "  ctl.O = embed.I;",
              "  embed.O = b0.I;"]
    lines += [f"  b{i}.O = b{i + 1}.I;" for i in range(n - 1)]
    lines += [f"  b{n - 1}.O = final_norm.I;",
              "  final_norm.O = lm_head.I;",
              "  lm_head.O = select.I;",
              "  select.O = ctl.I;",
              "}"]
    return "\n" + "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) == 3 and argv[0] == "layer":
        top, out = top_layer(int(argv[1])), Path(argv[2])
    elif len(argv) == 2 and argv[0] == "model":
        top, out = top_model(), Path(argv[1])
    else:
        print(__doc__, file=sys.stderr)
        return 2
    lib = (ROOT / "graph" / "qwen_lib.act").read_text()
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f"// Generated by scripts/gen_graph.py {' '.join(argv[:-1])}; do not edit.\n\n{lib}{top}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
